"""Renders fixtures/worked_example.md from the reference engine outputs (no hand-typed numbers).
Run after reference_engine.py: python render_worked_example.py"""
from __future__ import annotations

import json
from datetime import timedelta
from pathlib import Path

import reference_engine as R

HERE = Path(__file__).parent


def load(cid):
    return json.loads((HERE / "cases" / f"{cid}.json").read_text(encoding="utf-8"))


def exp(cid):
    return json.loads((HERE / "expected" / f"{cid}.json").read_text(encoding="utf-8"))


def k(x):
    return R.fmt(x, 2)


def strategy_by_id(case, sid):
    for st in R.enumerate_strategies(dict(case, sensitivity=[]), {}):
        if st.id == sid:
            return st
    raise KeyError(sid)


def timeline(case, st, sc):
    events, meta = R.build_events(case, st, sc)
    as_of = R.d(case["as_of"])
    end = R.horizon_end(case)
    series = R.sweep(case["opening_balance"], events, as_of, end)
    rows = sorted(events, key=lambda e: (e.date, 0 if e.direction == "out" else 1, e.id))
    return series, rows, meta


def main():
    out = []
    w = out.append
    c = load("OF-02")
    a = exp("OF-02")
    o = c["order"]
    w("# Worked example (generated)\n")
    w(f"Generated by `render_worked_example.py` from `expected/` with `{R.CALC_VERSION}`. Case `OF-02`, currency {c['currency']} (all amounts illustrative, synthetic).\n")
    w("## Inputs\n")
    w(f"- As-of date {c['as_of']}; opening balance {k(c['opening_balance'])}; minimum reserve {k(c['reserve'])} (hard constraint on every calendar day, relative to the baseline).")
    w(f"- Order {o['id']}: revenue {k(o['revenue'])}; terms: {o['terms']['days']} days from {o['terms']['anchor']} (delivery {o['anchor_dates']['delivery']}) -> customer payment date {R.d(o['anchor_dates'][o['terms']['anchor']]) + timedelta(days=o['terms']['days'])} (`expected`).")
    w("- Incremental order costs: " + "; ".join(f"{x['id']} {k(x['amount'])} on {x['date']}" + (" (deferrable)" if x.get("deferrable") else "") for x in o["costs"]))
    inc = sum(x["amount"] for x in o["costs"])
    w(f"- Order profit before financing = {k(o['revenue'])} - {k(inc)} = {k(o['revenue'] - inc)}.")
    w(f"- Customer concession for a deposit (user-supplied assumption): {o.get('deposit_discount_bps_per_10pct', 0)} bps of revenue per 10 points of deposit (a 40% deposit costs {k(R.apply_bps(o['revenue'], o.get('deposit_discount_bps_per_10pct', 0) * 4))}).")
    for f in c["financing_offers"]:
        w(f"- Financing offer {f['offer_id']} ({f['shape']}), user-supplied: " + ", ".join(f"{x}={y}" for x, y in f.items() if x not in ("offer_id", "name", "shape")))
    sc = c["scenarios"]
    w(f"- Scenarios (assumed, editable): downside = {json.dumps(sc['downside'])}; severe = {json.dumps(sc['severe'])}; the deposit is delayed together with the customer's payment. Target resilience: `{c['owner']['target_scenario']}`.")
    w("- Baseline events (existing obligations and expected collections); 'ar_collection' events are `expected`, all others `confirmed`:")
    for e in sorted(c["baseline_events"], key=lambda e: e["date"]):
        w(f"  - {e['date']} {e['direction']:>3} {k(e['amount']):>14} {e['kind']} ({e['certainty']})")
    w("\n## Counterfactual: baseline versus accept-as-is\n")
    b = a["baseline"]["base"]
    ai = a["accept_as_is"]["base"]
    w(f"- Baseline lowest balance {k(b['lowest_balance'])} on {b['lowest_date']} (reserve {k(c['reserve'])}): pre-existing breach = {b['absolute_gap_vs_reserve'] > 0}.")
    w(f"- Accept as-is: lowest balance {k(ai['lowest_balance'])} on {ai['lowest_date']}; first day below reserve {ai['first_shortfall_date']}; maximum funding gap {k(ai['max_funding_gap'])}; order-caused violation days {ai['order_caused_violation_days']}.")
    w("\n## Strategy comparison (hard-feasible after dominance pruning, ranked)\n")
    w("| Rank | Strategy | Dependencies | Net order profit | Financing cost | Headroom base | Headroom downside | Headroom severe | Resilience level | Meets target |")
    w("|---:|---|---|---:|---:|---:|---:|---:|---:|---|")
    for i, t in enumerate(a["ranked_top"], 1):
        w(f"| {i} | `{t['strategy_id']}` | {', '.join(t['dependencies']) or 'none'} | {k(t['net_order_profit'])} | {k(t['financing_cost'])} | {k(t['base']['headroom'])} | {k(t['downside']['headroom'])} | {k(t['severe']['headroom'])} | {t['resilience']} | {t['meets_target_resilience']} |")
    w("")
    w("Named strategies (hard-constraint verdicts):\n")
    w("| Label | Passes hard constraints | Failures | Tolerance (days late) | Net profit | Lowest base | Lowest downside |")
    w("|---|---|---|---:|---:|---:|---:|")
    for n in a["named"]:
        w(f"| {n['label']} | {n['passes_hard_constraints']} | {', '.join(n['hard_failures']) or '-'} | {n['delay_scan']['tolerance_days']} | {k(n['net_order_profit'])} | {k(n['base']['lowest_balance'])} | {k(n['downside']['lowest_balance'])} |")
    w("")
    w(f"Decision: `{a['decision']}`; recommended `{a['recommended']}`; best plan without financing `{a.get('best_without_financing')}`; the highest-profit hard-feasible plan is `{a['best_profit_strategy']}`; profit given up for resilience {k(a['profit_given_up_for_resilience'])}; escalations {[e['code'] for e in a['escalations']] or 'none'}.")
    w(f"Counts: {json.dumps(a['counts'])}; rejected by reason {json.dumps(a['hard_rejection_reasons'])}.\n")
    w("## Best plan by customer payment delay (linear scan; plans that hold at that delay, ranked by the owner's priorities)\n")
    for ch in a["best_plan_by_receipt_delay"]["changes"]:
        w(f"- from {ch['from_delay_days']} days late the best plan is `{ch['top']}`")
    w("")
    w("This is a different question from the recommendation: only the customer is delayed here (the other customers pay on time) and the first priority is profit; the recommendation uses the full downside scenario and the owner's target resilience.\n")
    w("## Sensitivity of the recommendation to the assumed parameters\n")
    s = a["assumption_sensitivity"]
    w(f"Baseline recommendation: `{s['baseline_recommended']}`. Each row changes one assumed parameter and re-runs the whole analysis.\n")
    w("| Parameter | Value | Recommended | Escalations |")
    w("|---|---:|---|---|")
    for r in s["runs"]:
        w(f"| `{r['path']}` | {r['value']} | `{r['recommended']}` | {', '.join(r['escalations']) or '-'} |")
    w("")
    w("## Alerts (reference implementation of A1, A2 and A6)\n")
    for who, al in a["alerts"].items():
        w(f"- {who}: " + (json.dumps(al) if al else "none"))
    w("")
    w("## Dated timeline for the highest-profit plan and the recommended plan (base scenario)\n")
    for sid in (a["best_profit_strategy"], a["recommended"]):
        st = strategy_by_id(c, sid)
        series, rows, meta = timeline(c, st, R.BASE_SC)
        w(f"### `{sid}`  (financing cost {k(meta['financing_cost'])}, concession {k(meta['discount'])})\n")
        w("| Date | Event | Amount | Certainty | Balance at the end of the day |")
        w("|---|---|---:|---|---:|")
        for e in rows:
            sign = "-" if e.direction == "out" else "+"
            w(f"| {e.date} | {e.id} ({e.kind}) | {sign}{k(e.amount)} | {e.certainty} | {k(series[e.date][1])} |")
        w("")
    w("## The same two plans in the downside scenario\n")
    for sid in (a["best_profit_strategy"], a["recommended"]):
        st = strategy_by_id(c, sid)
        series, rows, meta = timeline(c, st, c["scenarios"]["downside"])
        lo = min((tr, dy) for dy, (tr, _) in series.items())
        w(f"- `{sid}`: lowest balance {k(lo[0])} on {lo[1]} (reserve {k(c['reserve'])}); customer payment {next(e.date for e in rows if e.kind == 'order_final_receipt')}"
          + (f"; loan repayment {next(e.date for e in rows if e.kind == 'loan_repayment')}" if st.offer_id else ""))
    w("")
    w("## Two orders with similar profit, different decisions (OF-02 versus OF-15)\n")
    for cid in ("OF-02", "OF-15"):
        x = exp(cid)
        cc = load(cid)
        w(f"- {cid}: revenue {k(cc['order']['revenue'])}; order profit before financing {k(x['profit_summary']['order_profit_before_financing'])}; accept-as-is lowest balance {k(x['accept_as_is']['base']['lowest_balance'])}; decision `{x['decision']}`, recommended `{x['recommended']}`.")
    w("")
    w("## The owner's target changes the answer (OF-07A versus OF-07B, same inputs)\n")
    for cid in ("OF-07A", "OF-07B"):
        x = exp(cid)
        cc = load(cid)
        w(f"- {cid}: priorities {cc['owner']['priorities']}, target resilience `{cc['owner']['target_scenario']}` -> recommended `{x['recommended']}`; escalations {[e['code'] for e in x['escalations']] or 'none'}")
    w("")
    w("## Demo variants\n")
    for cid in ("DEMO-ASK", "DEMO-REPLY"):
        x = exp(cid)
        w(f"- {cid}: decision `{x['decision']}`, recommended `{x.get('recommended')}`, escalations {[e['code'] for e in x['escalations']]}")
        if x.get("voi"):
            for v in x["voi"]:
                w(f"  - value of information on `{v['input']}`: " + "; ".join(f"{lab}: `{r['recommended']}`" for lab, r in v["alternatives"].items()) + f" (flips: {v['flips_decision']})")
        for e in x["escalations"]:
            if e["code"] == "E-FRAGILE-BEST":
                w(f"  - a deposit-only plan would be robust at {e['customer_deposit_pct_that_would_make_a_deposit_only_plan_robust']}%")
    w("")
    (HERE / "worked_example.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote worked_example.md")


if __name__ == "__main__":
    main()
