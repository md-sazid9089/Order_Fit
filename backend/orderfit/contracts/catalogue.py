@dataclass(frozen=True)
class Endpoint:
    method: str
    path: str
    operation_id: str
    request: type[DTO] | None
    response: type[DTO]
    status: int
    permission: str
    service: str
    storage: str
    phase: str
    verification: str
    collection: bool = False
    multipart: bool = False
    # The body may be absent, JSON null or the request model (used for EmptyRequest commands).
    optional_body: bool = False


ROOT = "/api/v1/businesses/{business_id}"
ENDPOINTS: list[Endpoint] = []


def add(
    method,
    path,
    name,
    request,
    response,
    permission,
    service,
    storage,
    phase,
    verification,
    *,
    status=200,
    collection=False,
    multipart=False,
    optional_body=False,
):
    ENDPOINTS.append(
        Endpoint(
            method,
            path if path.startswith("/") else ROOT + "/" + path,
            name,
            request,
            response,
            status,
            permission,
            service,
            storage,
            phase,
            verification,
            collection,
            multipart,
            optional_body,
        )
    )


